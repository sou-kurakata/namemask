    "豈-﫿"  # CJK 互換漢字
    "\U00020000-\U0002a6df"  # CJK 拡張B（異体字・拡張漢字, astral）
    "\U0002a700-\U0002ebef"  # CJK 拡張C〜F（astral）
    "︀-️"  # 異体字セレクタ VS1-16
