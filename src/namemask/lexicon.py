# 同一表記伝播の境界判定に使う「名称連続」文字クラス（ひらがなは助詞なので除外）。
# 伝播先の前後がこのクラスの文字なら複合語内部とみなし伝播しない。
#
# 漢字は BMP の基本ブロックだけでなく、CJK 拡張A・拡張B〜F（異体字 𠮷 等の astral）・
# 互換漢字・異体字セレクタ（IVS）まで含める。基本ブロック（U+9FA5 まで）だけだと
# 拡張漢字を含む固有名詞（例: 𠮷野）の途中で伝播ガードが外れ、複合語内部へ食い込む
# 穴が残るため。可読性と安全のため全て \u/\U エスケープで書く
# （raw 文字列だと \U が展開されないので通常文字列）。
# 割り切り（ADR 相当メモ）: 結合文字を伴う特殊表記や、漢字・カナ以外の稀少スクリプト
# はなお完全ではないが、日本語ビジネス文書の名称連続判定としては十分広い。
