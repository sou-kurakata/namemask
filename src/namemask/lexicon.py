# 人名: 漢字・カタカナ・長音・英字（ひらがな除外）。
PERSON_NAME_CLASS = r"一-龥ァ-ヶーA-Za-z々"


def strip_legal_form(name: str) -> tuple[str | None, str]:
    """名称から法人格を1つ剥がしてコア名を返す。

    戻り値: (剥がした法人格 or None, コア名)。前置・後置の両方を試す。
    """
    for lf in LEGAL_FORMS:
        if name.startswith(lf):
            return lf, name[len(lf) :]
        if name.endswith(lf):
            return lf, name[: -len(lf)]
    return None, name
